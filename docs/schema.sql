-- يوزرسيف — مخطط قاعدة البيانات (PostgreSQL 15+)
-- اتولّد من نفس تعريف صفحة الـ ERD. القيم اللي بين [ ] محتاجة تأكيد.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TYPE staff_status AS ENUM ('active', 'pending', 'paused');
CREATE TYPE request_status AS ENUM ('pending', 'granted', 'denied');
CREATE TYPE option_type AS ENUM ('color', 'size', 'place');
CREATE TYPE org_type AS ENUM ('biz', 'group');
CREATE TYPE customer_type AS ENUM ('person', 'biz', 'group');
CREATE TYPE order_status AS ENUM ('submitted', 'in_review', 'awaiting_customer', 'approved', 'rejected', 'in_production', 'ready', 'delivered', 'cancelled');
CREATE TYPE biz_stage AS ENUM ('quote', 'customer_approval', 'mockup', 'deposit', 'production', 'qc', 'delivery', 'done');
CREATE TYPE receipt_method AS ENUM ('pickup', 'delivery');
CREATE TYPE file_kind AS ENUM ('design', 'reference', 'names_sheet', 'mockup');
CREATE TYPE quote_status AS ENUM ('draft', 'pending_admin', 'sent', 'accepted', 'declined', 'expired');
CREATE TYPE mockup_status AS ENUM ('with_desk', 'sent', 'approved', 'changes_requested');
CREATE TYPE production_stage AS ENUM ('queue', 'printing', 'qc', 'ready');
CREATE TYPE payment_kind AS ENUM ('deposit', 'balance', 'full');
CREATE TYPE payment_status AS ENUM ('pending_admin', 'confirmed', 'rejected');
CREATE TYPE delivery_status AS ENUM ('ready', 'delivered');
CREATE TYPE message_status AS ENUM ('prepared', 'sent', 'delivered', 'failed');

-- الأدوار: مدير، استقبال طلبات، مصمم، إنتاج، تسليم وتحصيل
CREATE TABLE roles (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key text NOT NULL UNIQUE,  -- admin · desk · design · prod · delivery
  name_ar text NOT NULL  -- اسم الدور بالعربي
);

-- الصلاحيات التفصيلية زي «رؤية رقم العميل» و«الموافقة النهائية»
CREATE TABLE permissions (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key text NOT NULL UNIQUE,  -- orders · phone · quote · approve · mockup · production · payment …
  label_ar text NOT NULL,
  group_key text NOT NULL  -- orders · execution · site
);

-- مصفوفة الأدوار × الصلاحيات. المدير عنده كله دايمًا
CREATE TABLE role_permissions (
  role_id smallint NOT NULL REFERENCES roles(id),
  permission_id smallint NOT NULL REFERENCES permissions(id),
  PRIMARY KEY (role_id, permission_id)
);

-- أعضاء التيم اللي بيدخلوا لوحة الإدارة
CREATE TABLE staff_users (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  name text NOT NULL,
  phone text NOT NULL UNIQUE,
  email text UNIQUE,
  role_id smallint NOT NULL REFERENCES roles(id),
  status staff_status NOT NULL,  -- active · pending · paused
  two_factor_enabled boolean NOT NULL DEFAULT false,
  last_active_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON staff_users (role_id);

-- دعوات الأعضاء الجدد
CREATE TABLE invitations (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  contact text NOT NULL,  -- موبايل أو إيميل
  role_id smallint NOT NULL REFERENCES roles(id),
  invited_by uuid NOT NULL REFERENCES staff_users(id),
  token_hash text NOT NULL UNIQUE,  -- الرابط نفسه مش بيتخزن
  expires_at timestamptz NOT NULL,  -- [المدة للتأكيد]
  accepted_at timestamptz
);
CREATE INDEX ON invitations (role_id);
CREATE INDEX ON invitations (invited_by);

-- الأجهزة المسجّل منها دخول
CREATE TABLE staff_sessions (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES staff_users(id),
  device_label text NOT NULL,
  city text,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz
);
CREATE INDEX ON staff_sessions (user_id);

-- لما عضو يطلب صلاحية من صفحة «مش ضمن صلاحياتك»
CREATE TABLE permission_requests (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES staff_users(id),
  permission_id smallint NOT NULL REFERENCES permissions(id),
  status request_status NOT NULL,  -- pending · granted · denied
  decided_by uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  decided_at timestamptz
);
CREATE INDEX ON permission_requests (user_id);
CREATE INDEX ON permission_requests (permission_id);
CREATE INDEX ON permission_requests (decided_by);

-- كل شخص عمل طلب
CREATE TABLE customers (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  name text NOT NULL,
  phone text NOT NULL UNIQUE,  -- بيتطابق مع كود التحقق
  email text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- شركة أو محل أو فريق أو جهة
CREATE TABLE organizations (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  name text NOT NULL,
  type org_type NOT NULL,  -- biz · group
  tax_id text,  -- بطاقة ضريبية أو سجل تجاري
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ملابس، مجات وهدايا، كفرات، استيكرات، فكرة خاصة
CREATE TABLE product_categories (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key text NOT NULL UNIQUE,  -- wear · mug · phone · sticker · custom
  name_ar text NOT NULL,
  image_url text NOT NULL,
  sort_order smallint NOT NULL,
  is_visible boolean NOT NULL DEFAULT false
);

-- تيشيرت، هودي، سويتشيرت، كاب، مج، مطرة…
CREATE TABLE products (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id smallint NOT NULL REFERENCES product_categories(id),
  key text NOT NULL UNIQUE,
  name_ar text NOT NULL,
  description text,
  image_url text,  -- صورة المنتج؛ لو فاضية بتظهر صورة التصنيف
  is_visible boolean NOT NULL DEFAULT false,  -- الأسعار مش ظاهرة للعميل
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON products (category_id);

-- الطلب الواحد بكل خطواته
CREATE TABLE orders (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  ref text NOT NULL UNIQUE,  -- YZ-XXXXXX اللي العميل بيشوفه
  idempotency_key_hash text UNIQUE,  -- HMAC لمفتاح إرسال العميل (منع التكرار)
  customer_id uuid NOT NULL REFERENCES customers(id),
  organization_id uuid REFERENCES organizations(id) ON DELETE SET NULL,  -- للشركات والفرق بس
  customer_type customer_type NOT NULL,  -- person · biz · group
  category_id smallint NOT NULL REFERENCES product_categories(id),
  product_id smallint REFERENCES products(id) ON DELETE SET NULL,
  status order_status NOT NULL,  -- submitted · in_review · awaiting_customer · approved · rejected · in_production · ready · delivered · cancelled
  biz_stage biz_stage,  -- quote · customer_approval · mockup · deposit · production · qc · delivery · done
  quantity int,
  color text,
  phone_model text,  -- للكفرات
  width numeric,  -- للاستيكرات
  height numeric,
  unit text,  -- cm · mm
  shape text,
  custom_text text,
  description text,  -- للفكرة الخاصة
  notes text,
  needs_design_help boolean NOT NULL DEFAULT false,
  design_notes text,
  wants_sample boolean NOT NULL DEFAULT false,
  per_piece_names boolean NOT NULL DEFAULT false,
  batched_delivery boolean NOT NULL DEFAULT false,
  batch_notes text,
  needs_invoice boolean NOT NULL DEFAULT false,
  receipt_method receipt_method NOT NULL,  -- pickup · delivery
  delivery_address text,
  desired_date date,  -- مرغوب، مش مؤكد
  final_price numeric,  -- للأفراد بعد الموافقة
  promised_date date,
  assigned_to uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  rejection_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON orders (customer_id);
CREATE INDEX ON orders (organization_id);
CREATE INDEX ON orders (category_id);
CREATE INDEX ON orders (product_id);
CREATE INDEX ON orders (assigned_to);

-- سجل نشاط الفريق اللي الأدمن بيشوفه، ومعاه الوصول للبيانات الحساسة
CREATE TABLE activity_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  action text NOT NULL,  -- مثلًا quote.submitted · phone.viewed
  entity_type text NOT NULL,
  entity_id text NOT NULL,
  order_id uuid REFERENCES orders(id) ON DELETE SET NULL,
  is_sensitive boolean NOT NULL DEFAULT false,  -- فتح رقم عميل أو بيانات دفع
  meta jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON activity_logs (user_id);
CREATE INDEX ON activity_logs (order_id);

-- الألوان والمقاسات وأماكن الطباعة المتاحة لكل منتج
CREATE TABLE product_options (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id smallint NOT NULL REFERENCES products(id),
  type option_type NOT NULL,  -- color · size · place
  value text NOT NULL,  -- white · XL · front …
  label_ar text NOT NULL,
  sort_order smallint NOT NULL
);
CREATE INDEX ON product_options (product_id);

-- مين بيتكلم باسم الجهة، وصفته
CREATE TABLE organization_contacts (
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  customer_id uuid NOT NULL REFERENCES customers(id),
  title text,  -- مثلًا: صاحب المحل
  PRIMARY KEY (organization_id, customer_id)
);

-- توزيع المقاسات
CREATE TABLE order_sizes (
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  size text NOT NULL,  -- S · M · L · XL · XXL
  qty int NOT NULL,  -- المجموع لازم يساوي orders.quantity
  PRIMARY KEY (order_id, size)
);

-- أماكن الطباعة المختارة
CREATE TABLE order_print_places (
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  place text NOT NULL,  -- front · back · sleeve
  PRIMARY KEY (order_id, place)
);

-- ملفات العميل، الصور المرجعية، شيت الأسماء، والموكابات
CREATE TABLE order_files (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  kind file_kind NOT NULL,  -- design · reference · names_sheet · mockup
  file_name text NOT NULL,
  mime_type text NOT NULL,
  size_bytes bigint NOT NULL,  -- حد 20 ميجا [للتأكيد]
  storage_key text NOT NULL,
  quality_flag text,  -- ok · low_res
  uploaded_by uuid REFERENCES staff_users(id) ON DELETE SET NULL,  -- فاضي = العميل رفعه
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON order_files (order_id);
CREATE INDEX ON order_files (uploaded_by);

-- رفع مؤقت قبل ما الطلب يتسجل (العميل مجهول). بيتنقل لـ order_files عند الإرسال
CREATE TABLE upload_drafts (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  submission_key_hash text NOT NULL,
  kind file_kind NOT NULL,  -- design · reference · names_sheet فقط (موكاب للفريق)
  file_name text NOT NULL,
  mime_type text NOT NULL,
  size_bytes bigint NOT NULL,
  storage_key text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT upload_drafts_kind_customer CHECK (kind IN ('design', 'reference', 'names_sheet'))
);
CREATE INDEX ON upload_drafts (submission_key_hash);
CREATE INDEX ON upload_drafts (expires_at);

-- سطر لكل قطعة من شيت الأسماء، والإنتاج بيعلّم عليه
CREATE TABLE order_pieces (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  seq int NOT NULL,
  name_text text,
  number_text text,
  size text,
  printed_at timestamptz
);
CREATE INDEX ON order_pieces (order_id);

-- التحديثات اللي بتظهر في صفحة التتبع
CREATE TABLE order_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  type text NOT NULL,
  title_ar text NOT NULL,  -- مثلًا «بدأت المراجعة»
  note text,
  visible_to_customer boolean NOT NULL DEFAULT false,
  actor_id uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON order_events (order_id);
CREATE INDEX ON order_events (actor_id);

-- عروض الأسعار: الاستقبال يجهّز، المدير يعتمد، العميل يوافق
CREATE TABLE quotes (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  version smallint NOT NULL,
  unit_price numeric NOT NULL,
  total numeric NOT NULL,
  lead_time_days smallint NOT NULL,
  valid_until date,  -- [الصلاحية للتأكيد]
  status quote_status NOT NULL,  -- draft · pending_admin · sent · accepted · declined · expired
  prepared_by uuid NOT NULL REFERENCES staff_users(id),
  approved_by uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  sent_at timestamptz,
  accepted_at timestamptz
);
CREATE INDEX ON quotes (order_id);
CREATE INDEX ON quotes (prepared_by);
CREATE INDEX ON quotes (approved_by);

-- نسخ الموكاب واعتماد العميل
CREATE TABLE mockups (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  version smallint NOT NULL,
  file_id uuid NOT NULL REFERENCES order_files(id),
  status mockup_status NOT NULL,  -- with_desk · sent · approved · changes_requested
  customer_feedback text,
  designer_id uuid NOT NULL REFERENCES staff_users(id),
  sent_at timestamptz,
  decided_at timestamptz
);
CREATE INDEX ON mockups (order_id);
CREATE INDEX ON mockups (file_id);
CREATE INDEX ON mockups (designer_id);

-- بورد الإنتاج: مرحلة لكل طلب، وعدّاد، وفحص جودة
CREATE TABLE production_jobs (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,  -- طلب واحد = شغلانة إنتاج واحدة
  stage production_stage NOT NULL,  -- queue · printing · qc · ready
  printed_count int NOT NULL,
  qc_sizes_ok boolean NOT NULL DEFAULT false,
  qc_names_ok boolean NOT NULL DEFAULT false,
  qc_print_ok boolean NOT NULL DEFAULT false,
  qc_count_ok boolean NOT NULL DEFAULT false,
  operator_id uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  started_at timestamptz,
  finished_at timestamptz
);
CREATE INDEX ON production_jobs (operator_id);

-- العربون والمتبقي. أي دفعة مستنية تأكيد المدير
CREATE TABLE payments (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  kind payment_kind NOT NULL,  -- deposit · balance · full
  amount numeric NOT NULL,
  method text NOT NULL,  -- cash · transfer [للتأكيد]
  status payment_status NOT NULL,  -- pending_admin · confirmed · rejected
  recorded_by uuid NOT NULL REFERENCES staff_users(id),
  confirmed_by uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  confirmed_at timestamptz
);
CREATE INDEX ON payments (order_id);
CREATE INDEX ON payments (recorded_by);
CREATE INDEX ON payments (confirmed_by);

-- التسليم، مرة واحدة أو على دفعات
CREATE TABLE deliveries (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  batch_no smallint NOT NULL,
  quantity int NOT NULL,
  status delivery_status NOT NULL,  -- ready · delivered
  failed_code_attempts smallint NOT NULL,  -- آخر 3 أرقام غلط
  delivered_by uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  delivered_at timestamptz
);
CREATE INDEX ON deliveries (order_id);
CREATE INDEX ON deliveries (delivered_by);

-- الفواتير باسم الجهة
CREATE TABLE invoices (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  organization_id uuid REFERENCES organizations(id) ON DELETE SET NULL,
  number text NOT NULL UNIQUE,
  type text NOT NULL,  -- [نوع الفاتورة للتأكيد]
  total numeric NOT NULL,
  issued_by uuid NOT NULL REFERENCES staff_users(id),
  issued_at timestamptz NOT NULL
);
CREATE INDEX ON invoices (order_id);
CREATE INDEX ON invoices (organization_id);
CREATE INDEX ON invoices (issued_by);

-- قوالب: موافقة، طلب بيانات، رفض، جاهز، عرض سعر، تحديث
CREATE TABLE message_templates (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key text NOT NULL UNIQUE,  -- approve · info · reject · ready · quote · update
  body text NOT NULL,  -- فيه متغيرات زي {name} {ref} {link}
  updated_by uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON message_templates (updated_by);

-- كل رسالة اتجهزت أو اتبعتت
CREATE TABLE messages (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  customer_id uuid NOT NULL REFERENCES customers(id),
  template_id smallint REFERENCES message_templates(id) ON DELETE SET NULL,
  channel text NOT NULL,  -- whatsapp · sms
  body text NOT NULL,
  status message_status NOT NULL,  -- prepared · sent · delivered · failed
  provider_message_id text,  -- بعد ربط واتساب للأعمال
  sent_by uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON messages (order_id);
CREATE INDEX ON messages (customer_id);
CREATE INDEX ON messages (template_id);
CREATE INDEX ON messages (sent_by);

-- لينك التتبع اللي في الرسالة
CREATE TABLE tracking_links (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,  -- اللينك فيه توكن، مش رقم الطلب بس
  expires_at timestamptz,
  last_opened_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON tracking_links (order_id);

-- كود الـ 6 أرقام اللي بيوصل قبل عرض الطلب
CREATE TABLE verification_codes (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  phone text NOT NULL,
  code_hash text NOT NULL,
  attempts smallint NOT NULL,
  expires_at timestamptz NOT NULL,
  verified_at timestamptz
);
CREATE INDEX ON verification_codes (order_id);

-- صور «أعمالنا». النشر مقفول من غير موافقة العميل
CREATE TABLE gallery_items (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid REFERENCES orders(id) ON DELETE SET NULL,
  image_url text NOT NULL,
  caption text,
  customer_consent boolean NOT NULL DEFAULT false,
  consent_at timestamptz,
  is_published boolean NOT NULL DEFAULT false,
  created_by uuid NOT NULL REFERENCES staff_users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON gallery_items (order_id);
CREATE INDEX ON gallery_items (created_by);

-- تقييمات العملاء الحقيقية بموافقتهم
CREATE TABLE reviews (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  customer_id uuid NOT NULL REFERENCES customers(id),
  body text NOT NULL,
  customer_consent boolean NOT NULL DEFAULT false,
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON reviews (order_id);
CREATE INDEX ON reviews (customer_id);

-- نصوص الهيرو وبيانات التواصل
CREATE TABLE site_content (
  key text PRIMARY KEY,  -- hero.title · contact.whatsapp …
  value text NOT NULL,
  updated_by uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON site_content (updated_by);

-- إعدادات الأمان والنظام
CREATE TABLE settings (
  key text PRIMARY KEY,  -- security.two_factor · security.timeout …
  value jsonb NOT NULL,
  updated_by uuid REFERENCES staff_users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON settings (updated_by);

