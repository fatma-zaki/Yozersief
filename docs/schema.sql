ALTER TABLE order_sizes ADD CONSTRAINT order_sizes_qty_pos CHECK (qty > 0);
CREATE INDEX ON orders (status, created_at DESC);
CREATE INDEX ON activity_logs (user_id, created_at DESC);
CREATE INDEX ON order_events (order_id, created_at DESC);
